#!/usr/bin/env python3
"""Coefficient tables for Android 4.4's VERY_HIGH_QUALITY converter (AudioResamplerSinc).

Android looks these up in libaudio-resampler.so. Layout, as AudioResamplerSinc reads it:
int32 table[(1 << coefsBits) + 1][halfNumCoefs]; row p, column k holds h(k + p / 2^coefsBits),
the right half of a symmetric impulse response sampled in input samples. Unity gain is 2^31
(the sum of all taps at any phase), the scale of Android's own tables, times GAIN below.

GAIN (-1.6 dB): Android adds (tap x sample) >> 16 for every tap into a 32-bit integer and does
not saturate. Its own 16-tap tables have sum|taps| <= 1.62 x 2^31, so that sum can never
overflow. A long, sharp filter at unity gain has sum|taps| of about 2.3 x 2^31: a pathological
full-scale input could then wrap around (a full-scale click). At GAIN the sum stays below
2 x 2^31 for every input, and the 1.6 dB also keeps peaks between samples (up to +1.6 dB) from
being cut off by Android's mixer.

down: for 48 kHz -> 44.1 kHz (Android Auto music): flat to 20 kHz, stopband from 24.1 kHz, so
      anything that folds back lands above 20 kHz. Normalised to the input rate.
up:   for 8..32 kHz -> 44.1 kHz (guidance voice, prompts): flat to 0.42 x the input rate,
      stopband from 0.50 x the input rate (no images above the input's Nyquist frequency).

Usage: gen_tables.py <halfNumCoefs> <coefsBits> <out.h>
"""
import sys
import numpy as np

H = int(sys.argv[1])          # taps on each side ("zero crossings" in Android's code)
BITS = int(sys.argv[2])       # phases = 2^BITS, linearly interpolated by Android
OUT = sys.argv[3]
GAIN = 10 ** (-1.6 / 20)      # -1.60 dB (x 0.8318), see above
L = 1 << BITS
assert H % 4 == 0, "Android's NEON path handles 4 taps at a time"


def kaiser_beta(atten):
    return 0.1102 * (atten - 8.7) if atten > 50 else 0.5842 * (atten - 21) ** 0.4 + 0.07886 * (atten - 21)


def design(fp, fs):
    """fp, fs in cycles per input sample. Returns the table and the design numbers."""
    fc = (fp + fs) / 2
    dw = 2 * np.pi * (fs - fp)
    atten = 2.285 * (2 * H - 1) * dw + 7.95          # what a Kaiser window of this length reaches
    beta = kaiser_beta(atten)
    p = np.arange(L + 1)[:, None] / L
    k = np.arange(H)[None, :]
    t = k + p                                         # distance from the output point, in input samples
    w = np.where(np.abs(t) < H, np.i0(beta * np.sqrt(np.clip(1 - (t / H) ** 2, 0, 1))) / np.i0(beta), 0.0)
    h = 2 * fc * np.sinc(2 * fc * t) * w
    # unity gain: average over phases of the sum of all taps (right half at p, left half at L - p)
    dc = np.mean([h[q].sum() + h[L - q].sum() for q in range(L + 1)])
    h = h / dc * GAIN
    tab = np.round(h * 2 ** 31)
    assert np.abs(tab).max() < 2 ** 31, "a tap does not fit in int32"
    tab = tab.astype(np.int64)
    # headroom: Android adds (tap x sample) >> 16 for every tap into an int32
    # Android interpolates each side between two neighbouring rows, so bound each side by the
    # larger of its two rows: positive side rows q, q+1; negative side rows L-q-1, L-q.
    S = np.abs(tab).sum(axis=1)
    worst = max(max(S[q], S[q + 1]) + max(S[L - q - 1], S[L - q]) for q in range(L))
    return tab, dict(fc=fc, atten=atten, beta=beta, worst_sum_abs=worst / 2 ** 31)


down, ddown = design(20000 / 48000, 24100 / 48000)
up, dup = design(0.42, 0.50)
for name, d in (("down", ddown), ("up", dup)):
    print("%-4s cutoff %.4f, Kaiser beta %.2f (design %.0f dB), sum|taps| %.3f x 2^31 (must stay below 2.0)"
          % (name, d["fc"], d["beta"], d["atten"], d["worst_sum_abs"]))
for name, d in (("down", ddown), ("up", dup)):
    assert d["worst_sum_abs"] < 1.98, name + ": the 32-bit sum could overflow"


def emit(f, name, tab):
    f.write("static const int32_t %s[%d][%d] __attribute__((aligned(32))) = {\n" % (name, L + 1, H))
    for row in tab:
        f.write("    {" + ", ".join("%d" % v for v in row) + "},\n")
    f.write("};\n\n")


with open(OUT, "w") as f:
    f.write("/* Generated by gen_tables.py %d %d: do not edit. */\n" % (H, BITS))
    f.write("#define VHQ_HALF_NUM_COEFS %d\n#define VHQ_COEFS_BITS %d\n\n" % (H, BITS))
    f.write("/* down: 48 -> 44.1 kHz, cutoff %.5f, beta %.3f; up: cutoff %.5f, beta %.3f */\n"
            % (ddown["fc"], ddown["beta"], dup["fc"], dup["beta"]))
    emit(f, "vhq_down", down)
    emit(f, "vhq_up", up)
print("wrote", OUT, "(%d KB of tables)" % ((L + 1) * H * 4 * 2 // 1024))
