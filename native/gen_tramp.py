#!/usr/bin/env python3
"""Writes the driver watch's forwarders for Hyundai's exported helper functions.

Usage: gen_tramp.py <names.txt> <out.S> <out_tab.c>

Each name gets an ARM function that jumps straight to Hyundai's function of the same name (so
arguments, stack and return values pass untouched), or returns 0 if it could not be found.
Position independent: the slot is reached relative to pc, so there are no text relocations.
"""
import re, sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
for n in names:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n):
        sys.exit("bad name %r" % n)

asm = ["@ generated by gen_tramp.py: forwarders to Hyundai's driver", "    .syntax unified", "    .arm", "    .text"]
for i, n in enumerate(names):
    asm += [
        "    .global %s" % n,
        "    .type %s, %%function" % n,
        "    .balign 4",
        "%s:" % n,
        "    ldr ip, .Lo%d" % i,
        ".Lp%d:" % i,
        "    add ip, pc, ip",
        "    ldr ip, [ip]",
        "    cmp ip, #0",
        "    bxne ip",
        "    mov r0, #0",
        "    bx lr",
        ".Lo%d:" % i,
        "    .word drvwatch_t_%s - (.Lp%d + 8)" % (n, i),
        "    .size %s, .-%s" % (n, n),
    ]
asm.append('    .section .note.GNU-stack,"",%progbits')
open(sys.argv[2], "w").write("\n".join(asm) + "\n")

c = ["/* generated by gen_tramp.py */", "#include <dlfcn.h>", "#include <stddef.h>", ""]
for n in names:
    c.append('__attribute__((visibility("hidden"))) void *drvwatch_t_%s;' % n)
c += ["", "static const struct {", "    const char *name;", "    void **slot;", "} tab[] = {"]
for n in names:
    c.append('    {"%s", &drvwatch_t_%s},' % (n, n))
c += [
    "};",
    "",
    "int drvwatch_tramp_count = (int)(sizeof(tab) / sizeof(tab[0]));",
    "",
    "/* returns how many of Hyundai's helper functions were found */",
    "int drvwatch_tramp_resolve(void *so) {",
    "    int found = 0;",
    "    for (size_t i = 0; i < sizeof(tab) / sizeof(tab[0]); i++) {",
    "        *tab[i].slot = dlsym(so, tab[i].name);",
    "        if (*tab[i].slot != NULL) found++;",
    "    }",
    "    return found;",
    "}",
]
open(sys.argv[3], "w").write("\n".join(c) + "\n")
